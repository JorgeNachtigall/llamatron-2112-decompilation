/* generated/assets_blob.c: every file under data/ as a C array, so the native binary needs no
 * files at run time (PLAN §2.2). Entry type LlamaBlobEntry comes from src/platform/asset_blob.h.
 * Deterministic: sorted by name, no timestamps or paths. */
#include "extract.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define DATA_PREFIX "data/"

static int compare_names(const void *a, const void *b)
{
    return strcmp(*(const char *const *)a, *(const char *const *)b);
}

static bool append_text(ByteBuf *out, const char *text)
{
    return bytebuf_append(out, (const uint8_t *)text, strlen(text));
}

static bool append_array(ByteBuf *out, size_t index, const ByteBuf *data)
{
    char line[160];
    snprintf(line, sizeof line, "static const unsigned char asset%zu[%zu] = {\n", index, data->size);
    bool ok = append_text(out, line);
    for (size_t i = 0; ok && i < data->size; i += 16) {
        size_t len = 0;
        line[len++] = ' ';
        for (size_t j = i; j < i + 16 && j < data->size; j++)
            len += (size_t)snprintf(line + len, sizeof line - len, " 0x%02x,", data->data[j]);
        line[len++] = '\n';
        ok = bytebuf_append(out, (const uint8_t *)line, len);
    }
    return ok && append_text(out, "};\n\n");
}

bool write_assets_blob(ExtractContext *ctx)
{
    OutputSet *outputs = ctx->outputs;
    const char *names[MAX_OUTPUTS];
    size_t sizes[MAX_OUTPUTS];
    size_t count = 0;
    for (size_t i = 0; i < outputs->count; i++)
        if (strncmp(outputs->records[i].path, DATA_PREFIX, strlen(DATA_PREFIX)) == 0)
            names[count++] = outputs->records[i].path;
    qsort(names, count, sizeof *names, compare_names);

    ByteBuf source = {0}, data = {0};
    bool ok = append_text(&source,
        "/* Generated by llamatron-extract from the user's own copy of Llamatron 2112.\n"
        " * Contains the original game's assets: personal use only, never distribute. */\n"
        "#include \"asset_blob.h\"\n\n");
    for (size_t i = 0; ok && i < count; i++) {
        char path[4096];
        ok = path_join(path, sizeof path, outputs->root, names[i]) && read_file(path, &data);
        if (ok && data.size == 0)
            ok = fail("%s is empty", names[i]);
        ok = ok && append_array(&source, i, &data);
        sizes[i] = data.size;
    }
    ok = ok && append_text(&source, "const LlamaBlobEntry llama_blob_entries[] = {\n");
    for (size_t i = 0; ok && i < count; i++) {
        char line[512];
        snprintf(line, sizeof line, "    {\"%s\", asset%zu, %zuUL},\n", names[i] + strlen(DATA_PREFIX), i,
                 sizes[i]);
        ok = ok && append_text(&source, line);
    }
    char tail[128];
    snprintf(tail, sizeof tail, "};\nconst unsigned llama_blob_count = %zu;\n", count);
    ok = ok && append_text(&source, tail) &&
         output_write(outputs, "assets_blob.c", source.data, source.size);
    bytebuf_free(&source);
    bytebuf_free(&data);
    return ok;
}

bool index_define(ExtractContext *ctx, const char *name, unsigned long value)
{
    if (ctx->define_count == MAX_INDEX_DEFINES)
        return fail("too many asset_index.h defines");
    ctx->defines[ctx->define_count++] = (IndexDefine){name, value};
    return true;
}

/* "title_vga.idx8" -> "TITLE_VGA_IDX8" */
static void macro_name(const char *file, char *out, size_t out_size)
{
    size_t len = 0;
    for (; *file && len + 1 < out_size; file++)
        out[len++] = (*file >= 'a' && *file <= 'z') ? (char)(*file - 'a' + 'A')
                     : (*file >= '0' && *file <= '9') || (*file >= 'A' && *file <= 'Z') ? *file : '_';
    out[len] = '\0';
}

bool write_asset_index(ExtractContext *ctx)
{
    static const struct {
        const char *magic;
        int version;
    } formats[] = {
        {"LFNT", FMT_LFNT_VERSION}, {"LSPR", FMT_LSPR_VERSION}, {"LSRF", FMT_LSRF_VERSION},
        {"LSMP", FMT_LSMP_VERSION}, {"LPAL", FMT_LPAL_VERSION}, {"LSCO", FMT_LSCO_VERSION},
        {"LCFG", FMT_LCFG_VERSION}, {"LTXT", FMT_LTXT_VERSION}, {"LLVL", FMT_LLVL_VERSION}, {"LHUD", FMT_LHUD_VERSION}, {"LHSC", FMT_LHSC_VERSION}, {"LENM", FMT_LENM_VERSION},
    };
    OutputSet *outputs = ctx->outputs;
    const char *names[MAX_OUTPUTS];
    size_t sizes[MAX_OUTPUTS];
    size_t count = 0;
    for (size_t i = 0; i < outputs->count; i++) {
        if (strncmp(outputs->records[i].path, DATA_PREFIX, strlen(DATA_PREFIX)) != 0)
            continue;
        char path[4096];
        ByteBuf data = {0};
        if (!path_join(path, sizeof path, outputs->root, outputs->records[i].path) || !read_file(path, &data))
            return false;
        names[count] = outputs->records[i].path + strlen(DATA_PREFIX);
        sizes[count++] = data.size;
        bytebuf_free(&data);
    }

    ByteBuf text = {0};
    char line[256], macro[128];
    bool ok = append_text(&text,
        "/* Generated by llamatron-extract (tools/extract/blob.c). Do not edit, do not commit.\n"
        " * Shared header: layout changes go through docs/CHANGELOG-shared.md. */\n"
        "#ifndef LLAMATRON_ASSET_INDEX_H\n#define LLAMATRON_ASSET_INDEX_H\n\n"
        "/* Data files (asset_get() names) and their sizes in bytes. */\n");
    for (size_t i = 0; ok && i < count; i++) {
        macro_name(names[i], macro, sizeof macro);
        snprintf(line, sizeof line, "#define LLAMA_ASSET_%s \"%s\"\n#define LLAMA_ASSET_%s_SIZE %zuu\n",
                 macro, names[i], macro, sizes[i]);
        ok = append_text(&text, line);
    }
    ok = ok && append_text(&text, "\n/* Format versions (tools/extract/FORMATS.md). */\n");
    for (size_t i = 0; ok && i < sizeof formats / sizeof *formats; i++) {
        snprintf(line, sizeof line, "#define LLAMA_FMT_%s_VERSION %d\n", formats[i].magic, formats[i].version);
        ok = append_text(&text, line);
    }
    ok = ok && append_text(&text, "\n/* Key counts. */\n");
    for (size_t i = 0; ok && i < ctx->define_count; i++) {
        snprintf(line, sizeof line, "#define LLAMA_%s %luu\n", ctx->defines[i].name, ctx->defines[i].value);
        ok = append_text(&text, line);
    }
    ok = ok && append_text(&text, "\n#endif /* LLAMATRON_ASSET_INDEX_H */\n") &&
         output_write(outputs, "asset_index.h", text.data, text.size);
    bytebuf_free(&text);
    return ok;
}
