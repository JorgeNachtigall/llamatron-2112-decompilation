/* generated/assets_blob.c: every file under data/ as a C array, so the native binary needs no
 * files at run time (PLAN §2.2). Entry type LlamaBlobEntry comes from src/platform/asset_blob.h.
 * Deterministic: sorted by name, no timestamps or paths. */
#include "extract.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define DATA_PREFIX "data/"

static int compare_names(const void *a, const void *b)
{
    return strcmp(*(const char *const *)a, *(const char *const *)b);
}

static bool append_text(ByteBuf *out, const char *text)
{
    return bytebuf_append(out, (const uint8_t *)text, strlen(text));
}

static bool append_array(ByteBuf *out, size_t index, const ByteBuf *data)
{
    char line[160];
    snprintf(line, sizeof line, "static const unsigned char asset%zu[%zu] = {\n", index, data->size);
    bool ok = append_text(out, line);
    for (size_t i = 0; ok && i < data->size; i += 16) {
        size_t len = 0;
        line[len++] = ' ';
        for (size_t j = i; j < i + 16 && j < data->size; j++)
            len += (size_t)snprintf(line + len, sizeof line - len, " 0x%02x,", data->data[j]);
        line[len++] = '\n';
        ok = bytebuf_append(out, (const uint8_t *)line, len);
    }
    return ok && append_text(out, "};\n\n");
}

bool write_assets_blob(ExtractContext *ctx)
{
    OutputSet *outputs = ctx->outputs;
    const char *names[MAX_OUTPUTS];
    size_t sizes[MAX_OUTPUTS];
    size_t count = 0;
    for (size_t i = 0; i < outputs->count; i++)
        if (strncmp(outputs->records[i].path, DATA_PREFIX, strlen(DATA_PREFIX)) == 0)
            names[count++] = outputs->records[i].path;
    qsort(names, count, sizeof *names, compare_names);

    ByteBuf source = {0}, data = {0};
    bool ok = append_text(&source,
        "/* Generated by llamatron-extract from the user's own copy of Llamatron 2112.\n"
        " * Contains the original game's assets: personal use only, never distribute. */\n"
        "#include \"asset_blob.h\"\n\n");
    for (size_t i = 0; ok && i < count; i++) {
        char path[4096];
        ok = path_join(path, sizeof path, outputs->root, names[i]) && read_file(path, &data);
        if (ok && data.size == 0)
            ok = fail("%s is empty", names[i]);
        ok = ok && append_array(&source, i, &data);
        sizes[i] = data.size;
    }
    ok = ok && append_text(&source, "const LlamaBlobEntry llama_blob_entries[] = {\n");
    for (size_t i = 0; ok && i < count; i++) {
        char line[512];
        snprintf(line, sizeof line, "    {\"%s\", asset%zu, %zuUL},\n", names[i] + strlen(DATA_PREFIX), i,
                 sizes[i]);
        ok = ok && append_text(&source, line);
    }
    char tail[128];
    snprintf(tail, sizeof tail, "};\nconst unsigned llama_blob_count = %zu;\n", count);
    ok = ok && append_text(&source, tail) &&
         output_write(outputs, "assets_blob.c", source.data, source.size);
    bytebuf_free(&source);
    bytebuf_free(&data);
    return ok;
}
